#!/usr/bin/env bash
# Bootstrap a fresh NixOS machine for this flake.
#
# Generates /etc/nixos/local.nix from the installer-generated config:
#   - LUKS devices declared in configuration.nix but not hardware-configuration.nix
#   - system.stateVersion
#   - NVIDIA driver + PRIME bus IDs, if an NVIDIA GPU is detected
# then runs the first flake rebuild (with flakes enabled inline).
#
# Run as your normal user; sudo is invoked where needed.
# DRY_RUN=1 ./bootstrap.sh prints the generated local.nix without writing
# or rebuilding.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INSTALLER_CONFIG=/etc/nixos/configuration.nix
HW_CONFIG=/etc/nixos/hardware-configuration.nix
LOCAL_NIX=/etc/nixos/local.nix
DRY_RUN=${DRY_RUN:-0}

if [[ ! -f $HW_CONFIG ]]; then
    echo "error: $HW_CONFIG not found — is this a NixOS system?" >&2
    exit 1
fi
if [[ $EUID -eq 0 ]]; then
    echo "error: run as your normal user, not root (sudo is used where needed)" >&2
    exit 1
fi

# --- LUKS devices the installer put in configuration.nix ---------------------
# hardware-configuration.nix already covers the root device on most installs;
# only carry over devices it does not declare (typically encrypted swap).
luks_lines=""
if [[ -f $INSTALLER_CONFIG ]]; then
    while IFS= read -r line; do
        name=$(sed -nE 's/.*luks\.devices\."([^"]+)".*/\1/p' <<<"$line")
        [[ -n $name ]] || continue
        if ! grep -q "luks.devices.\"$name\"" "$HW_CONFIG"; then
            luks_lines+="  $(sed -E 's/^\s+//' <<<"$line")"$'\n'
        fi
    done < <(grep -E '^\s*boot\.initrd\.luks\.devices' "$INSTALLER_CONFIG" || true)
fi

# --- stateVersion -------------------------------------------------------------
state_version=$(grep -oE 'system\.stateVersion *= *"[^"]+"' "$INSTALLER_CONFIG" 2>/dev/null \
    | grep -oE '"[^"]+"' | tr -d '"' || true)
if [[ -z $state_version ]]; then
    state_version=$(nixos-version | grep -oE '^[0-9]+\.[0-9]+')
    echo "note: no stateVersion in $INSTALLER_CONFIG, using current release $state_version"
fi

# --- GPU detection ------------------------------------------------------------
# PRIME bus IDs use decimal, lspci uses hex: 3a:00.0 -> PCI:58:0:0
to_prime() {
    local bus=${1%%:*} rest=${1#*:}
    printf 'PCI:%d:%d:%d' "0x$bus" "0x${rest%%.*}" "0x${rest#*.}"
}

gpus=$(lspci -nn | grep -Ei 'VGA compatible controller|3D controller|Display controller' || true)
nvidia_addr=$(grep -i '\[10de:' <<<"$gpus" | head -1 | cut -d' ' -f1 || true)
intel_addr=$(grep -i '\[8086:'  <<<"$gpus" | head -1 | cut -d' ' -f1 || true)
amd_addr=$(grep -i '\[1002:'    <<<"$gpus" | head -1 | cut -d' ' -f1 || true)

nvidia_section=""
if [[ -n $nvidia_addr ]]; then
    echo "detected NVIDIA GPU at $nvidia_addr"
    nvidia_section+="  imports = [ $REPO_DIR/nixos/nvidia.nix ];"$'\n\n'
    if [[ -n $intel_addr || -n $amd_addr ]]; then
        # Hybrid graphics: enable PRIME sync against the integrated GPU.
        nvidia_section+="  hardware.nvidia.prime = {"$'\n'
        nvidia_section+="    nvidiaBusId = \"$(to_prime "$nvidia_addr")\";"$'\n'
        if [[ -n $intel_addr ]]; then
            nvidia_section+="    intelBusId  = \"$(to_prime "$intel_addr")\";"$'\n'
        else
            nvidia_section+="    amdgpuBusId = \"$(to_prime "$amd_addr")\";"$'\n'
        fi
        nvidia_section+="    sync.enable = true;"$'\n'
        nvidia_section+="  };"$'\n'
    fi
elif [[ -n $gpus ]]; then
    echo "no NVIDIA GPU detected; Intel/AMD graphics work without extra config"
fi

# --- generate local.nix ---------------------------------------------------------
local_nix=$(cat <<EOF
# Machine-specific configuration for this host.
# Generated by bootstrap.sh — not part of the dotfiles repo.
{ ... }:

{
${nvidia_section}${luks_lines}
  system.stateVersion = "$state_version";
}
EOF
)

echo
echo "--- generated $LOCAL_NIX ---"
echo "$local_nix"
echo "----------------------------"

if [[ $DRY_RUN == 1 ]]; then
    echo "dry run: nothing written, no rebuild"
    exit 0
fi

if [[ -f $LOCAL_NIX ]]; then
    echo "warning: $LOCAL_NIX already exists; it will be backed up to local.nix.bak"
fi
read -rp "Write this file? [y/N] " answer
[[ $answer == [yY]* ]] || exit 1
[[ -f $LOCAL_NIX ]] && sudo cp "$LOCAL_NIX" "$LOCAL_NIX.bak"
echo "$local_nix" | sudo tee "$LOCAL_NIX" > /dev/null

read -rp "Run the first rebuild now (nixos-rebuild switch)? [y/N] " answer
[[ $answer == [yY]* ]] || { echo "done — rebuild later with: sudo nixos-rebuild switch --flake $REPO_DIR#nixos --impure"; exit 0; }
sudo env NIX_CONFIG="experimental-features = nix-command flakes" \
    nixos-rebuild switch --flake "$REPO_DIR#nixos" --impure
